import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const siteUrl = 'https://www.johncalhounelectric.com/';
const ignoredDirectories = new Set(['.git', 'node_modules']);

async function findIndexPages(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const pages = [];

  for (const entry of entries) {
    const pathname = join(directory, entry.name);
    if (entry.isDirectory() && !ignoredDirectories.has(entry.name)) {
      pages.push(...await findIndexPages(pathname));
    } else if (entry.isFile() && entry.name === 'index.html') {
      pages.push(pathname);
    }
  }

  return pages;
}

function getAttribute(tag, name) {
  const match = tag.match(new RegExp(`\\b${name}\\s*=\\s*(["'])(.*?)\\1`, 'i'));
  return match?.[2] ?? '';
}

function getCanonical(html) {
  for (const match of html.matchAll(/<link\b[^>]*>/gi)) {
    if (getAttribute(match[0], 'rel').toLowerCase().split(/\s+/).includes('canonical')) {
      return getAttribute(match[0], 'href');
    }
  }
  return '';
}

function isNoindex(html) {
  return [...html.matchAll(/<meta\b[^>]*>/gi)].some(match => {
    const name = getAttribute(match[0], 'name').toLowerCase();
    const content = getAttribute(match[0], 'content').toLowerCase();
    return name === 'robots' && content.split(/[\s,]+/).includes('noindex');
  });
}

function expectedUrlFor(file) {
  const directory = relative(root, dirname(file)).split(sep).join('/');
  return directory ? new URL(`${directory}/`, siteUrl).href : siteUrl;
}

function escapeXml(value) {
  return value
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&apos;');
}

const urls = [];
for (const file of await findIndexPages(root)) {
  const html = await readFile(file, 'utf8');
  if (isNoindex(html)) continue;

  const canonical = getCanonical(html);
  const expected = expectedUrlFor(file);
  if (!canonical) throw new Error(`${relative(root, file)} is indexable but has no canonical URL.`);
  if (canonical !== expected) {
    throw new Error(`${relative(root, file)} has canonical ${canonical}; expected ${expected}.`);
  }
  urls.push(canonical);
}

urls.sort((a, b) => {
  if (a === siteUrl) return -1;
  if (b === siteUrl) return 1;
  return a.localeCompare(b);
});

if (new Set(urls).size !== urls.length) throw new Error('Duplicate canonical URLs found.');

const xml = [
  '<?xml version="1.0" encoding="UTF-8"?>',
  '<!-- Generated by `node generate-sitemap.mjs`; do not edit by hand. -->',
  '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
  ...urls.map(url => `  <url><loc>${escapeXml(url)}</loc></url>`),
  '</urlset>',
  ''
].join('\n');

await writeFile(join(root, 'sitemap.xml'), xml, 'utf8');
console.log(`Generated sitemap.xml with ${urls.length} canonical, indexable URLs.`);
